for (const id of hunterIds) {
  if (!hunters.some((hunter) => hunter.id === id)) {
    throw new Error(`Missing hunter: ${id}`);
  }
}

export function getHunter(id: string) {
  return hunters.find((hunter) => hunter.id === id);
}

export function getNeighbors(id: HunterId) {
  const index = hunters.findIndex((hunter) => hunter.id === id);
  return {
    prev: hunters[(index - 1 + hunters.length) % hunters.length],
    next: hunters[(index + 1) % hunters.length],
  };
}
